umur = 25
if umur < 2:
    print("Orang ini masih bayi.")
elif umur < 4:
    print("Orang ini masih balita.")
elif umur < 13:
    print("Orang ini masih anak-anak.")
elif umur < 20:
    print("Orang ini masih remaja.")
elif umur < 65:
    print("Orang ini sudah dewasa.")
else: 
    print("Orang ini sudah lansia.")